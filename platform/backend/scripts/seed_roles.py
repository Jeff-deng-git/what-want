def main():
    provider = "deepseek"
    model = "deepseek-v4-flash"
    with get_conn() as conn:
        for role in ROLES:
            existing = conn.execute(
                "SELECT id FROM llm_roles WHERE name = ? AND provider = ? AND enabled = 1",
                (role["name"], provider),
            ).fetchone()
            if existing:
                # Idempotent refresh: keep id stable, refresh model + system_prompt + updated_at.
                conn.execute(
                    "UPDATE llm_roles SET description = ?, model = ?, system_prompt = ?, "
                    "temperature = ?, max_tokens = ?, updated_at = datetime('now') WHERE id = ?",
                    (role["description"], model, role["system_prompt"],
                     role["temperature"], role["max_tokens"], existing["id"]),
                )
                print("updated:", role["name"])
                continue
            conn.execute(
                """INSERT INTO llm_roles
                   (id, name, description, system_prompt, provider, model,
                    temperature, max_tokens, enabled)
                   VALUES (?, ?, ?, ?, ?, ?, ?, ?, 1)""",
                (str(uuid.uuid4()), role["name"], role["description"],
                 role["system_prompt"], provider, model,
                 role["temperature"], role["max_tokens"]),
            )
            print("seeded:", role["name"])


